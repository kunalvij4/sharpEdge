from datetime import datetime
from typing import Protocol

from odds_api.domain.models import Board, League


class Clock(Protocol):
    def monotonic(self) -> float: ...
    def now(self) -> datetime: ...
    async def sleep(self, seconds: float) -> None: ...


class Provider(Protocol):
    async def fetch(self, league_key: str, kind: str) -> Board: ...
    async def close(self) -> None: ...


class Repository(Protocol):
    def save(self, board: Board) -> None: ...
    def failure(self, league: str, kind: str, outcome: str) -> None: ...
    def missed(self, league: str, kind: str, count: int, lag: float) -> None: ...
    def leagues(self) -> list[League]: ...
    def events(self, sport: str) -> list[dict]: ...
    def quotes(self, sport: str) -> list[dict]: ...
    def bookmakers(self) -> set[str]: ...
    def status(self, now: datetime, collected_ttl: float, source_ttl: float) -> dict: ...
    def ready(self) -> bool: ...
